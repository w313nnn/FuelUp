import React from "react";
import { afterEach, expect, it, vi } from "vitest";
import { act, cleanup, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { NearbyDining } from "../src/components/NearbyDining";
import { FuelUpProvider } from "../src/state/FuelUpProvider";
import { createSeed } from "../src/data/seed";
import * as places from "../src/services/places";
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
const venue: places.NearbyPlace = { id: "node/100", name: "Mapped bistro", lat: 3.123, lon: 101.65, distance: 150, address: "Campus road", cuisine: "salad", tags: { amenity: "restaurant", cuisine: "salad", "diet:vegetarian": "yes" } };
const drinkVenue: places.NearbyPlace = { ...venue, id: "node/101", name: "Mapped cafe", cuisine: "coffee", tags: { amenity: "cafe", cuisine: "coffee_shop" } };
const start = (save = async (_state: ReturnType<typeof createSeed>) => {}) => render(<FuelUpProvider repository={{ load: async () => createSeed(), save }}><NearbyDining now={new Date()} gap={45} /></FuelUpProvider>);
it("looks up GPS results, links their coordinates and logs actual spending", async () => {
  vi.spyOn(places, "locate").mockResolvedValue({ lat: 3.12, lon: 101.65 });
  vi.spyOn(places, "fetchPlaces").mockResolvedValue([venue]);
  const user = userEvent.setup(); start();
  await user.click(await screen.findByRole("button", { name: "Use my current location" }));
  const link = await screen.findByRole("link", { name: /Walk there with Google Maps/ });
  const url = new URL(link.getAttribute("href")!);
  expect(url.searchParams.get("origin")).toBe("3.12,101.65");
  expect(url.searchParams.get("destination")).toBe("3.123,101.65");
  await user.click(screen.getByRole("button", { name: "Log a meal here" }));
  await user.type(screen.getByLabelText("Amount paid (RM)"), "6.50");
  await user.click(screen.getByRole("button", { name: "Log meal", exact: true }));
  expect(await screen.findByText("Meal logged.")).toBeTruthy();
  expect(screen.getByText(/13.50 left today/)).toBeTruthy();
});
it("provides a usable Maps fallback when location is denied", async () => {
  vi.spyOn(places, "locate").mockRejectedValue(new Error("Location denied. Search your area instead."));
  const lookup = vi.spyOn(places, "fetchPlaces");
  const user = userEvent.setup(); start();
  await user.click(await screen.findByRole("button", { name: "Use my current location" }));
  expect(await screen.findByRole("alert")).toBeTruthy();
  expect(lookup).not.toHaveBeenCalled();
  expect(screen.getByRole("link", { name: "Search Google Maps" }).getAttribute("href")).toContain("healthy+meals+restaurants+near+me");
});
it("filters existing results immediately and never substitutes fake places", async () => {
  vi.spyOn(places, "locate").mockResolvedValue({ lat: 3.12, lon: 101.65 });
  vi.spyOn(places, "fetchPlaces").mockResolvedValue([venue]);
  const user = userEvent.setup(); start();
  await user.click(await screen.findByRole("button", { name: "Use my current location" }));
  await screen.findByText("Mapped bistro");
  await user.click(screen.getByRole("button", { name: "Area & food preferences" }));
  await user.selectOptions(screen.getByLabelText("Food preference"), "vegan");
  expect(screen.queryByText("Mapped bistro")).toBeNull();
  expect(screen.getByText(/No mapped places match/)).toBeTruthy();
});
it("switches to drinks using the same location and records a drink separately", async () => {
  const locate = vi.spyOn(places, "locate").mockResolvedValue({ lat: 3.12, lon: 101.65 });
  const lookup = vi.spyOn(places, "fetchPlaces").mockImplementation(async (_p, _s, category) => category === "drinks" ? [drinkVenue] : [venue]);
  const save = vi.fn(async (_state: ReturnType<typeof createSeed>) => {});
  const user = userEvent.setup(); start(save);
  expect((await screen.findByRole("button", { name: "Food", exact: true })).getAttribute("aria-pressed")).toBe("true");
  await user.click(screen.getByRole("button", { name: "Use my current location" }));
  await screen.findByText("Mapped bistro");
  await user.click(screen.getByRole("button", { name: "Drinks", exact: true }));
  await screen.findByText("Mapped cafe");
  expect(locate).toHaveBeenCalledTimes(1);
  expect(lookup.mock.calls.at(-1)?.[2]).toBe("drinks");
  expect(screen.queryByText("Mapped bistro")).toBeNull();
  expect(screen.getByRole("button", { name: "Find a meal" })).toBeTruthy();
  await user.click(screen.getByRole("button", { name: "Log a drink here" }));
  await user.type(screen.getByLabelText("Amount paid (RM)"), "3");
  await user.click(screen.getByRole("button", { name: "Log drink", exact: true }));
  await screen.findByText("Drink logged. It won’t count as a meal.");
  await waitFor(() => expect(save.mock.calls.at(-1)?.[0].meals[0].kind).toBe("drink"));
  expect(screen.getByText(/17.00 left today/)).toBeTruthy();
});
it("ignores a late food response after the student switches to drinks", async () => {
  vi.spyOn(places, "locate").mockResolvedValue({ lat: 3.12, lon: 101.65 });
  let finishFood!: (results: places.NearbyPlace[]) => void;
  const lookup = vi.spyOn(places, "fetchPlaces").mockImplementation((_p, _s, category) => category === "drinks" ? Promise.resolve([drinkVenue]) : new Promise(resolve => { finishFood = resolve; }));
  const user = userEvent.setup(); start();
  await user.click(await screen.findByRole("button", { name: "Use my current location" }));
  await waitFor(() => expect(lookup).toHaveBeenCalledTimes(1));
  await user.click(screen.getByRole("button", { name: "Drinks", exact: true }));
  await screen.findByText("Mapped cafe");
  await act(async () => finishFood([venue]));
  expect(screen.getByText("Mapped cafe")).toBeTruthy();
  expect(screen.queryByText("Mapped bistro")).toBeNull();
});
